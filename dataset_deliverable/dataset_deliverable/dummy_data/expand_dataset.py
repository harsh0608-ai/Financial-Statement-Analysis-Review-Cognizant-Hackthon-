"""Runs the REAL backend pipeline (extraction -> normalization -> rule
engine) over the companies generated by generate_dataset.py, and appends
them to the existing dummy_finstatement.db (statements 1-5 from
seed_dummy_data.py are left untouched).

Usage:
    cd backend
    python3 dummy_data/generate_dataset.py   # (re)generates the PDFs
    python3 dummy_data/expand_dataset.py     # runs them through the pipeline

Respects an existing DATABASE_URL env var the same way seed_dummy_data.py
does; otherwise defaults to ./dummy_finstatement.db and does NOT wipe it,
since this is meant to sit alongside the original 5 seed statements.
"""
import csv
import os
import shutil
import sys
import time

DUMMY_DATA_DIR = os.path.dirname(os.path.abspath(__file__))
BACKEND_DIR = os.path.dirname(DUMMY_DATA_DIR)
sys.path.insert(0, BACKEND_DIR)

DEFAULT_DB_PATH = os.path.join(os.getcwd(), "dummy_finstatement.db")
if not os.getenv("DATABASE_URL"):
    os.environ["DATABASE_URL"] = f"sqlite:///{DEFAULT_DB_PATH}"

from config import ANALYTICAL_THRESHOLD_PERCENT, STORAGE_DIR, REPORT_DIR  # noqa: E402
from db.database import Base, SessionLocal, engine  # noqa: E402
from db import crud  # noqa: E402
from extraction.pdf_parser import extract_raw_content  # noqa: E402
from extraction.normalizer import normalize_extraction  # noqa: E402
from rules.engine import run_all_checks  # noqa: E402
from report.report_builder import build_report_html  # noqa: E402

from generate_dataset import generate_company_specs, build_company_pdfs  # noqa: E402

YEAR_COLUMNS = ["current_year", "prior_year"]
SUMMARY_CSV_PATH = os.path.join(DUMMY_DATA_DIR, "companies_dataset_summary.csv")


def _copy_into_storage(source_path: str) -> str:
    filename = os.path.basename(source_path)
    dest_path = os.path.join(STORAGE_DIR, filename)
    shutil.copyfile(source_path, dest_path)
    return dest_path


def _process_statement(db, filename, source_path, linked_prior_statement_id=None):
    filepath = _copy_into_storage(source_path)
    statement = crud.create_statement(
        db, filename=filename, filepath=filepath,
        linked_prior_statement_id=linked_prior_statement_id,
    )

    crud.update_statement_status(db, statement.id, "extracting")
    raw_content = extract_raw_content(filepath)
    structured_items = normalize_extraction(raw_content, YEAR_COLUMNS)
    crud.bulk_insert_line_items(db, statement.id, structured_items)

    crud.update_statement_status(db, statement.id, "reviewing")
    line_items = crud.get_line_items(db, statement.id)

    prior_statement_items = []
    if linked_prior_statement_id:
        prior_statement_items = crud.get_line_items(
            db, linked_prior_statement_id, year="current_year",
        )

    findings = run_all_checks(
        line_items, raw_content["pages_text"],
        prior_statement_items=prior_statement_items,
        analytical_threshold_percent=ANALYTICAL_THRESHOLD_PERCENT,
    )
    crud.bulk_insert_findings(db, statement.id, findings)

    stored_findings = crud.get_findings(db, statement.id)
    build_report_html(statement, stored_findings)

    crud.update_statement_status(db, statement.id, "done")

    return statement, stored_findings


def main(limit=None):
    Base.metadata.create_all(bind=engine)  # non-destructive; keeps existing rows

    specs = generate_company_specs()
    if limit:
        specs = specs[:limit]

    db = SessionLocal()
    summary_rows = []
    start = time.time()

    try:
        for i, company in enumerate(specs, start=1):
            baseline_path, current_path = build_company_pdfs(company)

            baseline_statement, baseline_findings = _process_statement(
                db,
                f"{company['id']}_signed_prior_year_FY2025.pdf",
                baseline_path,
            )
            current_statement, current_findings = _process_statement(
                db,
                f"{company['id']}_current_year_FY2026.pdf",
                current_path,
                linked_prior_statement_id=baseline_statement.id,
            )

            check_type_counts = {}
            for f in current_findings:
                check_type_counts[f.check_type] = check_type_counts.get(f.check_type, 0) + 1

            summary_rows.append({
                "company_id": company["id"],
                "company_name": company["name"],
                "industry": company["industry"],
                "category": company["category"],
                "baseline_statement_id": baseline_statement.id,
                "current_statement_id": current_statement.id,
                "baseline_findings": len(baseline_findings),
                "current_findings": len(current_findings),
                "mathematical_accuracy": check_type_counts.get("mathematical_accuracy", 0),
                "prior_year_tie_out": check_type_counts.get("prior_year_tie_out", 0),
                "internal_consistency": check_type_counts.get("internal_consistency", 0),
                "spell_grammar": check_type_counts.get("spell_grammar", 0),
                "analytical_review": check_type_counts.get("analytical_review", 0),
                "ratio_analysis": check_type_counts.get("ratio_analysis", 0),
                "wp514_checklist": check_type_counts.get("wp514_checklist", 0),
                "optional_disclosure_presence": check_type_counts.get("optional_disclosure_presence", 0),
            })

            elapsed = time.time() - start
            print(f"[{i}/{len(specs)}] {company['id']} {company['name']:<35} "
                  f"({company['category']:<28}) -> statements "
                  f"{baseline_statement.id},{current_statement.id}  "
                  f"findings: baseline={len(baseline_findings)} current={len(current_findings)}  "
                  f"[{elapsed:.1f}s elapsed]")

    finally:
        db.close()

    with open(SUMMARY_CSV_PATH, "w", newline="") as f:
        fieldnames = list(summary_rows[0].keys()) if summary_rows else []
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(summary_rows)

    print(f"\nProcessed {len(summary_rows)} companies in {time.time() - start:.1f}s")
    print(f"Database: {os.environ['DATABASE_URL']}")
    print(f"Reports:  {REPORT_DIR}")
    print(f"Summary CSV: {SUMMARY_CSV_PATH}")


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument("--limit", type=int, default=None, help="Only process the first N companies (for a quick test run).")
    args = parser.parse_args()
    main(limit=args.limit)
